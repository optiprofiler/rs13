import bam
import math

def _post(_v, _name, _delta):
    _old = _v.get(_name, 0)
    _v[_name] = _old + _delta
    return _old

def objective(xin):
    fout = 0.0
    _v = {}
    bam_idx = 0
    n = 50
    x = [0.0] * (51)
    obj = 0.0
    s = 0.0
    i = 0.0
    j = 0.0
    for j in range(1, (n) + 1):
        x[j] = xin[_post(_v, 'bam_idx', 1)]
    obj = 0.0e0
    for i in range(1, (n) + 1):
        s = 0.0e0
        for j in range(1, (n) + 1):
            s = s + x[j] / (i + j - 1)
        s = math.fabs(s)
        if s > obj:
            obj = s
    fout = obj
    return fout


