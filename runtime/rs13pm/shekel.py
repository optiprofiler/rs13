import bam

def objective(x):
    f = 0.0
    v = [0.0] * (4)
    v[0] = -4. + x[0]
    v[1] = v[0] * v[0]
    v[1] += 0.1
    v[0] = -4. + x[1]
    v[2] = v[0] * v[0]
    v[1] += v[2]
    v[2] = -4. + x[2]
    v[0] = v[2] * v[2]
    v[1] += v[0]
    v[0] = -4. + x[3]
    v[2] = v[0] * v[0]
    v[1] += v[2]
    v[2] = 1. / v[1]
    v[1] = -1. + x[0]
    v[0] = v[1] * v[1]
    v[0] += 0.2
    v[1] = -1. + x[1]
    v[3] = v[1] * v[1]
    v[0] += v[3]
    v[3] = -1. + x[2]
    v[1] = v[3] * v[3]
    v[0] += v[1]
    v[1] = -1. + x[3]
    v[3] = v[1] * v[1]
    v[0] += v[3]
    v[3] = 1. / v[0]
    v[2] += v[3]
    v[3] = -8. + x[0]
    v[0] = v[3] * v[3]
    v[0] += 0.2
    v[3] = -8. + x[1]
    v[1] = v[3] * v[3]
    v[0] += v[1]
    v[1] = -8. + x[2]
    v[3] = v[1] * v[1]
    v[0] += v[3]
    v[3] = -8. + x[3]
    v[1] = v[3] * v[3]
    v[0] += v[1]
    v[1] = 1. / v[0]
    v[2] += v[1]
    v[1] = -6. + x[0]
    v[0] = v[1] * v[1]
    v[0] += 0.4
    v[1] = -6. + x[1]
    v[3] = v[1] * v[1]
    v[0] += v[3]
    v[3] = -6. + x[2]
    v[1] = v[3] * v[3]
    v[0] += v[1]
    v[1] = -6. + x[3]
    v[3] = v[1] * v[1]
    v[0] += v[3]
    v[3] = 1. / v[0]
    v[2] += v[3]
    v[3] = -3. + x[0]
    v[0] = v[3] * v[3]
    v[0] += 0.4
    v[3] = -7. + x[1]
    v[1] = v[3] * v[3]
    v[0] += v[1]
    v[1] = -3. + x[2]
    v[3] = v[1] * v[1]
    v[0] += v[3]
    v[3] = -7. + x[3]
    v[1] = v[3] * v[3]
    v[0] += v[1]
    v[1] = 1. / v[0]
    v[2] += v[1]
    v[1] = -v[2]
    f = v[1]
    return f


xmin = [0, 0, 0, 0]
xmax = [10, 10, 10, 10]
x0 = [5, 5, 5, 5]

res = bam.minimize(objective, x0=x0,
                   bounds=list(zip(xmin, xmax)),
                   options={"tracefname": "shekel.trc"})

print("Status = %d" % res.status)
print("Best f = %.15e" % res.fun)
print("Best x = " + "".join("%.15e " % xi for xi in res.x))
